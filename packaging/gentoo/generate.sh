#!/usr/bin/env bash
# Writes the Gentoo ebuild media-gfx/froxel-bin (for the GURU overlay) and its
# Manifest for a release, from the release's Linux tarballs.
#
#   packaging/gentoo/generate.sh <version> <dir with the tarballs> <overlay-dir>
#
# It writes <overlay-dir>/media-gfx/froxel-bin/{froxel-bin-<version>.ebuild,
# Manifest,metadata.xml}. Prereleases need Gentoo's _rc version spelling and are
# not generated.
set -euo pipefail

version=${1:?version}
assets=${2:?assets dir}
overlay=${3:?overlay dir}
repo=${REPOSITORY:-theromis/Froxel}
url="https://github.com/$repo"
dir="$overlay/media-gfx/froxel-bin"
mkdir -p "$dir"

cat >"$dir/froxel-bin-$version.ebuild" <<EBUILD
# Copyright 2026 Gentoo Authors
# Distributed under the terms of the GNU General Public License v2
# Generated by packaging/gentoo/generate.sh in $url.

EAPI=8

inherit desktop xdg

DESCRIPTION="Voxel editor with a path tracer and an MCP server"
HOMEPAGE="$url"
SRC_URI="
	amd64? ( $url/releases/download/v\${PV}/froxel-\${PV}-linux-x86_64.tar.gz )
	arm64? ( $url/releases/download/v\${PV}/froxel-\${PV}-linux-aarch64.tar.gz )
	riscv? ( $url/releases/download/v\${PV}/froxel-\${PV}-linux-riscv64.tar.gz )
"
S="\${WORKDIR}"

LICENSE="MIT"
SLOT="0"
KEYWORDS="~amd64 ~arm64 ~riscv"
RESTRICT="strip"

RDEPEND="
	media-libs/vulkan-loader
	|| ( sys-devel/gcc llvm-runtimes/libgcc )
	sys-libs/glibc
	x11-libs/libxkbcommon
"

QA_PREBUILT="usr/bin/froxel"

src_install() {
	cd froxel-\${PV}-linux-* || die
	dobin froxel
	domenu froxel.desktop
	local png size
	for png in icons/*.png; do
		size=\$(basename "\${png}" .png)
		newicon -s "\${size%%x*}" "\${png}" froxel.png
	done
	insinto /usr/share/metainfo
	doins com.lonje.Froxel.metainfo.xml
	dodoc README.md
}
EBUILD

cat >"$dir/metadata.xml" <<XML
<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE pkgmetadata SYSTEM "https://www.gentoo.org/dtd/metadata.dtd">
<pkgmetadata>
	<maintainer type="person">
		<email>${MAINTAINER_EMAIL:-MAINTAINER_EMAIL}</email>
		<name>${MAINTAINER_NAME:-Froxel}</name>
	</maintainer>
	<upstream>
		<remote-id type="github">$repo</remote-id>
		<bugs-to>$url/issues</bugs-to>
	</upstream>
</pkgmetadata>
XML

: >"$dir/Manifest"
for a in x86_64 aarch64 riscv64; do
  f="$assets/froxel-$version-linux-$a.tar.gz"
  python3 -I - "$f" >>"$dir/Manifest" <<'PY'
import hashlib, os, sys
path = sys.argv[1]
data = open(path, "rb").read()
print("DIST", os.path.basename(path), len(data),
      "BLAKE2B", hashlib.blake2b(data).hexdigest(),
      "SHA512", hashlib.sha512(data).hexdigest())
PY
done
echo "wrote $dir"
