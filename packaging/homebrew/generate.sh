#!/usr/bin/env bash
# Writes the Homebrew tap files for a release: Casks/froxel.rb (the macOS app
# from the dmg) and Formula/froxel.rb (the Linux binary from the tarball).
#
#   packaging/homebrew/generate.sh <version> <SHA256SUMS.txt> <tap-dir>
#
# The tap is the repository <owner>/homebrew-froxel, so users run
#   brew install --cask <owner>/froxel/froxel    (macOS)
#   brew install <owner>/froxel/froxel           (Linux)
set -euo pipefail

version=${1:?version}
sums=${2:?SHA256SUMS.txt}
tap=${3:?tap dir}
repo=${REPOSITORY:-theromis/Froxel}
url="https://github.com/$repo"

sum() {
  local s
  s=$(awk -v f="$1" '$2 == f || $2 == "*" f { print $1 }' "$sums")
  if [ -z "$s" ]; then
    echo "no checksum for $1 in $sums" >&2
    exit 1
  fi
  printf '%s' "$s"
}

mkdir -p "$tap/Casks" "$tap/Formula"
cat >"$tap/Casks/froxel.rb" <<RUBY
# Generated by packaging/homebrew/generate.sh in $url; edit it there.
cask "froxel" do
  version "$version"
  sha256 "$(sum "froxel-$version-macos-universal.dmg")"

  url "$url/releases/download/v#{version}/froxel-#{version}-macos-universal.dmg"
  name "Froxel"
  desc "Voxel editor with a path tracer and an MCP server"
  homepage "$url"

  livecheck do
    url :url
    strategy :github_latest
  end

  depends_on :macos

  app "Froxel.app"
  binary "#{appdir}/Froxel.app/Contents/MacOS/froxel"

  zap trash: [
    "~/Library/Application Support/Froxel",
    "~/Library/Preferences/com.lonje.froxel.plist",
    "~/Library/Saved Application State/com.lonje.froxel.savedState",
  ]
end
RUBY

cat >"$tap/Formula/froxel.rb" <<RUBY
# Generated by packaging/homebrew/generate.sh in $url; edit it there.
# The Linux build; on macOS install the cask instead.
class Froxel < Formula
  desc "Voxel editor with a path tracer and an MCP server"
  homepage "$url"
  version "$version"
  license "MIT"

  livecheck do
    url :stable
    strategy :github_latest
  end

  depends_on :linux

  on_linux do
    on_intel do
      url "$url/releases/download/v#{version}/froxel-#{version}-linux-x86_64.tar.gz"
      sha256 "$(sum "froxel-$version-linux-x86_64.tar.gz")"
    end
    on_arm do
      url "$url/releases/download/v#{version}/froxel-#{version}-linux-aarch64.tar.gz"
      sha256 "$(sum "froxel-$version-linux-aarch64.tar.gz")"
    end
  end

  def install
    bin.install "froxel"
    share.install "froxel.desktop" => "applications/froxel.desktop"
    (share/"metainfo").install "com.lonje.Froxel.metainfo.xml"
    Dir["icons/*.png"].each do |png|
      (share/"icons/hicolor"/File.basename(png, ".png")/"apps").install png => "froxel.png"
    end
  end

  def caveats
    <<~EOS
      Froxel draws with Vulkan, so it needs your distribution's Vulkan loader
      and GPU driver (for example libvulkan1 and mesa-vulkan-drivers).
    EOS
  end

  test do
    assert_match "usage: froxel", shell_output("#{bin}/froxel --help")
  end
end
RUBY
echo "wrote $tap/Casks/froxel.rb and $tap/Formula/froxel.rb"
