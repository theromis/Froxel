#!/usr/bin/env bash
# Writes the AUR package froxel-bin (PKGBUILD and .SRCINFO) for a release.
#
#   packaging/linux/aur/generate.sh <version> <SHA256SUMS.txt> <out-dir>
#
# The package repacks the release tarballs, so the checksums come from the
# release's SHA256SUMS.txt. MAINTAINER ("Name <email>") goes in the header.
# Prereleases are not published to the AUR.
set -euo pipefail

version=${1:?version}
sums=${2:?SHA256SUMS.txt}
out=${3:?out-dir}
repo=${REPOSITORY:-theromis/Froxel}
url="https://github.com/$repo"
arches=(x86_64 aarch64 riscv64)

sum() {
  local file="froxel-$version-linux-$1.tar.gz" s
  s=$(awk -v f="$file" '$2 == f || $2 == "*" f { print $1 }' "$sums")
  if [ -z "$s" ]; then
    echo "no checksum for $file in $sums" >&2
    exit 1
  fi
  printf '%s' "$s"
}

mkdir -p "$out"
{
  if [ -n "${MAINTAINER:-}" ]; then echo "# Maintainer: $MAINTAINER"; fi
  cat <<HEAD
# Generated by packaging/linux/aur/generate.sh in $url; edit it there.
pkgname=froxel-bin
pkgver=$version
pkgrel=1
pkgdesc='Voxel editor with a path tracer and an MCP server'
arch=(${arches[*]})
url='$url'
license=(MIT)
depends=(glibc hicolor-icon-theme libgcc libxkbcommon vulkan-icd-loader)
optdepends=('wayland: Wayland sessions'
            'libx11: X11 sessions'
            'libxkbcommon-x11: X11 sessions'
            'xdg-desktop-portal: file dialogs'
            'vulkan-driver: GPU rendering')
provides=(froxel)
conflicts=(froxel)
options=(!strip !debug)
HEAD
  for a in "${arches[@]}"; do
    echo "source_$a=(\"$url/releases/download/v\$pkgver/froxel-\$pkgver-linux-$a.tar.gz\")"
  done
  for a in "${arches[@]}"; do
    echo "sha256sums_$a=('$(sum "$a")')"
  done
  cat <<'BODY'

package() {
  cd "froxel-$pkgver-linux-$CARCH"
  install -Dm755 froxel "$pkgdir/usr/bin/froxel"
  install -Dm644 froxel.desktop "$pkgdir/usr/share/applications/froxel.desktop"
  install -Dm644 com.lonje.Froxel.metainfo.xml "$pkgdir/usr/share/metainfo/com.lonje.Froxel.metainfo.xml"
  local png
  for png in icons/*.png; do
    install -Dm644 "$png" "$pkgdir/usr/share/icons/hicolor/$(basename "$png" .png)/apps/froxel.png"
  done
  install -Dm644 LICENSE "$pkgdir/usr/share/licenses/$pkgname/LICENSE"
  install -Dm644 README.md "$pkgdir/usr/share/doc/$pkgname/README.md"
}
BODY
} >"$out/PKGBUILD"

# .SRCINFO is what `makepkg --printsrcinfo` prints for this PKGBUILD.
{
  echo "pkgbase = froxel-bin"
  echo "	pkgdesc = Voxel editor with a path tracer and an MCP server"
  echo "	pkgver = $version"
  echo "	pkgrel = 1"
  echo "	url = $url"
  for a in "${arches[@]}"; do echo "	arch = $a"; done
  echo "	license = MIT"
  for d in glibc hicolor-icon-theme libgcc libxkbcommon vulkan-icd-loader; do echo "	depends = $d"; done
  echo "	optdepends = wayland: Wayland sessions"
  echo "	optdepends = libx11: X11 sessions"
  echo "	optdepends = libxkbcommon-x11: X11 sessions"
  echo "	optdepends = xdg-desktop-portal: file dialogs"
  echo "	optdepends = vulkan-driver: GPU rendering"
  echo "	provides = froxel"
  echo "	conflicts = froxel"
  echo "	options = !strip"
  echo "	options = !debug"
  for a in "${arches[@]}"; do
    echo "	source_$a = $url/releases/download/v$version/froxel-$version-linux-$a.tar.gz"
    echo "	sha256sums_$a = $(sum "$a")"
  done
  echo
  echo "pkgname = froxel-bin"
} >"$out/.SRCINFO"
echo "wrote $out/PKGBUILD and $out/.SRCINFO"
